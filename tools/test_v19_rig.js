const fs=require('fs'), vm=require('vm'), assert=require('assert');
const path=require('path');
const dir=path.resolve(__dirname,'../Mozdulj.Maui/Resources/Raw/rig3d');
const sandbox={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(dir,'engine.js'),'utf8'),sandbox);
const rig=sandbox.window.MozduljRig;
const pose=rig.initialPose('supine');
const base=pose.frames[0];
base.legAngles={right:{flexion:120*Math.PI/180,abduction:.1,kneeFlexion:0}};
base.footPitch={left:-.5,right:.7};
rig.checkPose(pose);
const j=rig.joints(base);
const d=(a,b)=>Math.hypot(...a.map((x,i)=>x-b[i]));
assert(Math.abs(d(j.hip.right,j.knee.right)-.45)<1e-5);
assert(Math.abs(d(j.knee.right,j.feet.right)-.43)<1e-5);
assert(Math.abs(d(j.feet.right,j.toes.right)-.18)<1e-5);
assert(j.feet.right[1]>j.hip.right[1], 'hanyatt fekve láb a csípő síkja fölé emelhető');
const ankle1=j.toes.right;
base.footPitch.right=-.5;
const j2=rig.joints(base);
assert(d(ankle1,j2.toes.right)>.1, 'pipa / spicc visibly different');
base.legAngles.right.flexion=3;
assert.throws(()=>rig.checkPose(pose));
console.log('PASS: 120° csípőemelés, állandó comb/lábszár/lábfej hosszak, pipa–spicc különbség, tartománykorlát');
